function classify(row) {
  const ep = row['Endpoint'];
  const stc = row['Test Case ID'];
  if (ep.startsWith('/api/admin/v1/')) return 'ADMIN';
  if (ep.startsWith('/api/v1/patient/')) return 'PATIENT';
  if (ep.startsWith('/auth/') || ep === '/healthz') return 'SHARED';
  return 'KINE';
}

function folderFor(row, collection) {
  const stc = row['Test Case ID'];
  const ep = row['Endpoint'];
  if (collection === 'ADMIN') {
    if (ep.includes('/auth/login')) return 'Auth';
    if (ep.includes('/kines/') && ep.includes('/profiles')) return 'Profiles Admin Add To Kine';
    if (ep.includes('/verification')) return 'Verification Kine';
  }
  if (collection === 'PATIENT') return 'Auth';
  if (collection === 'SHARED') {
    if (ep.includes('forgot')) return 'Password Forgot';
    if (ep.includes('verify-code')) return 'Password Verify Code';
    if (ep.includes('reset-password')) return 'Password Reset';
    if (ep.includes('change-password')) return 'Password Change';
    if (ep === '/healthz') return 'System Healthcheck';
  }
  if (collection === 'KINE') {
    if (stc.startsWith('STC-AUTH-KINE')) return 'Auth';
    if (stc.startsWith('STC-REGISTER')) return 'Registration';
    if (stc.startsWith('STC-INVIT-GEN') || stc.startsWith('STC-INVIT-ASST')) return 'Invitations Generate';
    if (stc.startsWith('STC-INVIT-ATTACH')) return 'Invitations Attach';
    if (stc.startsWith('STC-INVIT-ACCEPT')) return 'Invitations Accept';
    if (stc.startsWith('STC-PROFILE-SELECT')) return 'Profiles Select';
    if (stc.startsWith('STC-PROFILE-ADD')) return 'Profiles Add';
    if (stc.startsWith('STC-PROFILE-UPDATE')) return 'Profiles Update';
  }
  return 'Other';
}

function urlFromEndpoint(ep, row) {
  const stc = row['Test Case ID'];
  /** Swagger: GET / (root) health, SUPER_ADMIN Bearer — not /healthz */
  if (stc === 'STC-HEALTHZ-001/B') {
    return '{{baseUrl}}{{healthCheckPath}}';
  }
  let u = String(ep ?? '').trim();
  /** Legacy sheet used root /auth/* — Identity service uses /api/v1/kine/auth/* for shared password routes */
  if (u.startsWith('/auth/')) {
    u = '/api/v1/kine' + u;
  }
  u = u
    .replace(':id', '{{kineId}}')
    .replace(':profileId', '{{profileId}}');
  if (stc === 'STC-PROFILE-UPDATE-002/B') {
    u = '/api/v1/kine/profiles/65f0000000000000000000ff';
  }
  if (stc === 'STC-PROFILE-ADD-006/B') {
    u = '/api/admin/v1/kines/65f0000000000000000000ff/profiles';
  }
  return `{{baseUrl}}${u.startsWith('/') ? u : '/' + u}`;
}

function needsNoAuth(row) {
  const { tail } = splitPayload(row['Payload / Test Data']);
  return /no authorization/i.test(tail);
}

function authHeaderFromTail(tail) {
  if (/super_admin/i.test(tail)) return '{{adminToken}}';
  if (/kine_admin/i.test(tail)) return '{{kineToken}}';
  if (/member_or_assistant/i.test(tail)) return '{{kineToken}}';
  if (/admin_token/i.test(tail)) return '{{kineToken}}';
  /** Prefer kineToken for "wrong actor" on admin routes when PATIENT login has not run yet. */
  if (/kine_or_patient/i.test(tail)) return '{{kineToken}}';
  if (/inactive_kine/i.test(tail)) return '{{kineTokenInactive}}';
  if (/user_token/i.test(tail)) return '{{kineToken}}';
  return '{{kineToken}}';
}

function buildHeaders(row, collection) {
  const stc = row['Test Case ID'];
  if (stc === 'STC-HEALTHZ-001/B') {
    return [
      { key: 'Accept', value: 'application/json' },
      { key: 'Authorization', value: 'Bearer {{adminToken}}' },
    ];
  }
  const { body, tail } = splitPayload(row['Payload / Test Data']);
  const h = [{ key: 'Accept', value: 'application/json' }];
  const method = row['Method'].toUpperCase();
  if (method === 'GET' || method === 'HEAD') {
    if (!/multipart/i.test(body)) return h;
  }
  if (/multipart/i.test(body)) {
    return [{ key: 'Accept', value: 'application/json' }];
  }
  if (body && !/^no body/i.test(body) && !body.startsWith('/path/')) {
    h.push({ key: 'Content-Type', value: 'application/json' });
  }
  const ep = row['Endpoint'];
  const skipAuth =
    needsNoAuth(row) ||
    (ep.includes('/auth/login') && !ep.includes('select')) ||
    ep.includes('/auth/register') ||
    ep.includes('/auth/accept-invitation') ||
    ep.includes('/auth/invitations/attach') ||
    (ep.includes('/auth/forgot-password') || ep.includes('/auth/verify-code') || ep.includes('/auth/reset-password')) ||
    ep === '/healthz';

  if (!skipAuth) {
    const adminPath = collection === 'ADMIN' || ep.startsWith('/api/admin/');
    /** Sheet uses kine/patient token on admin URL to assert 403 (wrong actor). */
    const wrongActor =
      /kine_or_patient/i.test(tail) ||
      /patient_token/i.test(tail) ||
      /<kine_or_patient/i.test(tail);
    const token = adminPath && !wrongActor ? '{{adminToken}}' : authHeaderFromTail(tail);
    h.push({ key: 'Authorization', value: `Bearer ${token}` });
  }
  if (/<kine_token>/i.test(tail) || tail.includes('X-Profile-Id')) {
    if (!h.some((x) => x.key === 'Authorization')) {
      h.push({ key: 'Authorization', value: 'Bearer {{kineToken}}' });
    }
    if (/X-Profile-Id/i.test(tail)) {
      h.push({ key: 'X-Profile-Id', value: '{{profileId}}' });
    }
  }
  return h;
}

