function transformJsonForSwagger(obj, row) {
  if (!obj || typeof obj !== 'object' || Array.isArray(obj)) return obj;
  const ep = String(row['Endpoint'] ?? '');
  const method = String(row['Method'] ?? '').toUpperCase();
  if (ep.includes('/patient/') && ep.includes('auth/login') && obj.emailOrPhone != null) {
    obj.email = obj.emailOrPhone;
    delete obj.emailOrPhone;
  }
  /* Sheet maps shared password literal to {{kinePassword}}; patient nominal must use patientPassword. */
  if (
    ep.includes('/patient/') &&
    ep.includes('auth/login') &&
    obj.password === '{{kinePassword}}'
  ) {
    obj.password = '{{patientPassword}}';
  }
  if (
    ep.includes('kine/auth/invitations') &&
    !ep.includes('preview') &&
    !ep.includes('attach') &&
    obj.role != null &&
    obj.targetProfileType == null
  ) {
    obj.targetProfileType = obj.role;
    delete obj.role;
  }
  if (ep.includes('change-password')) {
    if (obj.oldPassword != null && obj.currentPassword == null) {
      obj.currentPassword = obj.oldPassword;
      delete obj.oldPassword;
    }
    if (obj.newPassword != null && obj.newPasswordConfirmation == null) {
      obj.newPasswordConfirmation = obj.newPassword;
    }
  }
  /** Admin add profile (cabinet-creating flows): API requires address fields + ObjectId plan */
  if (
    method === 'POST' &&
    ep.includes('/api/admin/v1/kines/') &&
    ep.includes('/profiles') &&
    obj.cabinetName != null &&
    String(obj.cabinetName).trim() !== '' &&
    obj.street == null
  ) {
    obj.street = '{{cabinetAddressStreet}}';
    obj.postalCode = obj.postalCode ?? '{{cabinetAddressPostalCode}}';
    obj.city = obj.city ?? '{{cabinetAddressCity}}';
  }
  return obj;
}

