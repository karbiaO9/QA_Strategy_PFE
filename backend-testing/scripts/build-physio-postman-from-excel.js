function splitPayload(raw) {
  const full = String(raw ?? '').trim();
  const idx = full.indexOf(' | ');
  if (idx === -1) return { body: full, tail: '' };
  return { body: full.slice(0, idx).trim(), tail: full.slice(idx + 3).trim() };
}

function stripComments(s) {
  return String(s)
    .replace(/\/\*[\s\S]*?\*\//g, ' ')
    .replace(/(^|[^:])\/\/.*$/gm, '$1');
}

function tryParseJson(s) {
  let t = stripComments(s).trim();
  if (!t.startsWith('{') && !t.startsWith('[')) return null;
  const ou = /\s+ou\s+/i.exec(t);
  if (ou) t = t.slice(0, ou.index).trim();
  try {
    return JSON.parse(t.replace(/,(\s*[}\]])/g, '$1'));
  } catch {
    return null;
  }
}

